--    바텐톡        → 금
--    바텐톡 위스키  → 은
--    바텐톡 칵테일  → 동
--  이름표는 셋 다 "관리자".
--
--  ⚠️ 댓글 다는 봇(페르소나)은 일부러 건드리지 않습니다.
