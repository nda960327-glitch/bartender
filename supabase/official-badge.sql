-- ------------------------------------------------------------
--  0. 먼저 확인 — 내 프로젝트의 계정 이름이 아래와 같은지 보세요
-- ------------------------------------------------------------
--  select id, nick, is_official, official_label, color, is_bot
--  from public.profiles
--  where is_official or is_bot order by nick;
--
--  이름이 다르면 아래 nick 값을 실제 이름으로 바꿔서 실행하세요.

-- ------------------------------------------------------------
--  1. 세 계정에 금·은·동 + '관리자' 붙이기
--     color 10 = 금, 11 = 은, 12 = 동  (앱의 COLORS 배열과 같은 번호)
-- ------------------------------------------------------------
update public.profiles set
  is_official    = true,
  official_label = '관리자',
  color          = v.color
from (values
  ('바텐톡',        10),
  ('바텐톡 위스키', 11),
  ('바텐톡 칵테일', 12)
) as v(nick, color)
where btrim(public.profiles.nick) = v.nick;

-- ------------------------------------------------------------
--  2. 이미 올라간 글에도 이름표를 새로 찍기
--
--  글의 공식 표시는 "쓰는 순간" 글에 복사됩니다 (앱이 목록을 빨리 그리려고요).
--  그래서 프로필만 고치면 예전 글은 옛 이름표 그대로예요. 여기서 맞춰줍니다.
--  색은 글이 아니라 사람에게 붙어 있어서 따로 손댈 필요가 없습니다.
-- ------------------------------------------------------------
update public.posts p set
  official       = true,
  official_label = '관리자'
from public.profiles pr
where pr.id = p.author_id
  and btrim(pr.nick) in ('바텐톡', '바텐톡 위스키', '바텐톡 칵테일');

