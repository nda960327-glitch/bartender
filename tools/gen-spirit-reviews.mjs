function readItems() {
  const s = fs.readFileSync(path.join(ROOT, "js/app.js"), "utf8");
  const out = [];
  for (const m of s.matchAll(/^\s*SP\((\d+),\s*"[^"]*",\s*"([^"]*)",\s*"([^"]*)"/gm))
    out.push({ id: +m[1], kind: "spirit", name: m[2], cat: m[3] });
  for (const m of s.matchAll(/^\s*CT\((\d+),\s*"[^"]*",\s*"([^"]*)",\s*"([^"]*)"/gm))
    out.push({ id: +m[1], kind: "cocktail", name: m[2], cat: m[3] });
  for (const m of s.matchAll(/\{ id: (\d+), kind: "spirit"[^\n]*?name: "([^"]*)"[^\n]*?cat: "([^"]*)"/g))
    out.push({ id: +m[1], kind: "spirit", name: m[2], cat: m[3] });
  for (const m of s.matchAll(/\{ id: (\d+), kind: "cocktail"[^\n]*?name: "([^"]*)"[^\n]*?base: "([^"]*)"/g))
    out.push({ id: +m[1], kind: "cocktail", name: m[2], cat: m[3] });
  const seen = new Set();
  return out.filter((x) => (seen.has(x.id) ? false : (seen.add(x.id), true)));
}

/* 같은 이름은 언제나 같은 값 (FNV-1a + 섞기).
   >>> 0 을 빼먹으면 음수가 나와서 나머지 연산이 망가집니다. */
function hash(str) {
  let h = 2166136261 >>> 0;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619) >>> 0;
  }
  h = (h ^ (h >>> 15)) >>> 0;
  h = Math.imul(h, 2246822507) >>> 0;
  h = (h ^ (h >>> 13)) >>> 0;
  return h;
}

